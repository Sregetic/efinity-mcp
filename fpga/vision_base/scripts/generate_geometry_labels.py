"""Rasterize M7 box captions into CPU constants, not an additional FPGA font RAM."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = Path('C:/Windows/Fonts/Noto Sans SC Medium (TrueType).otf')
TEXTS = ['圆形', '矩形', '人脸'] + list('ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz')
TEXTS += [f'{c}/{c.lower()}' for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'] + ['I/l']


def generate():
    chinese = ImageFont.truetype(str(FONT), 15)
    latin = ImageFont.truetype(str(FONT), 14)
    lines = ['/* Generated by scripts/generate_geometry_labels.py; Noto Sans SC Medium, Chinese15px/Latin14px. */',
             '#pragma once', '#include <stdint.h>', f'static const uint32_t m7_labels[{len(TEXTS)}][16]={{']
    widths = []; patterns = []
    for text in TEXTS:
        font = chinese if any(ord(c) >= 128 for c in text) else latin
        width = 16 if len(text) == 1 else 32
        box = font.getbbox(text); left = -min(0, box[0])
        assert box[2]+left <= width and box[1] >= 5 and box[3] <= 21, (text, box)
        im = Image.new('L', (32,16))
        ImageDraw.Draw(im).text((left,-5), text, font=font, fill=255)
        rows = [sum((im.getpixel((x,y)) >= 96) << x for x in range(width)) for y in range(16)]
        assert any(rows)
        lines.append(' {' + ','.join(f'0x{v:08x}u' for v in rows) + '}, // ' + text)
        widths.append(width)
        patterns.append(rows)
    lines += ['};', f'static const uint8_t m7_label_width[{len(TEXTS)}]={{' + ','.join(map(str,widths)) + '};',
              'static inline uint64_t m7_label_row(unsigned klass,unsigned row){',
              ' return klass ? m7_labels[klass-1][row]|((uint64_t)m7_label_width[klass-1]<<32) : 0;', '}', '']
    return '\n'.join(lines), patterns, widths


if __name__ == '__main__':
    source, patterns, widths = generate()
    (ROOT/'firmware/vision/geometry_labels.h').write_text(source, encoding='utf-8')
    fixture = [(widths[k-1]<<32)|v for k in (30,1,3,2) for v in patterns[k-1]]
    (ROOT/'sim/fixtures/m7_labels.mem').write_text('\n'.join(f'{v:010x}' for v in fixture)+'\n')
    print('Generated 82 captions in CPU constants; existing FPGA result RAM holds active rows.')
